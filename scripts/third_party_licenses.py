"""Generates THIRD_PARTY_LICENSES.md from Cargo metadata.

Usage (from the repo root, after a `cargo fetch` / build so sources exist):
    python -I scripts/third_party_licenses.py > docs/THIRD_PARTY_LICENSES.md

Lists every crate that is part of the Windows build (normal + build deps, no
dev deps) with its SPDX license, then the license / notice files shipped by
those crates, grouped by identical text. Vendored crates (vendor/*) are listed
as patched copies. Fonts and icons in assets/ are covered by assets/licenses.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

TARGET = "x86_64-pc-windows-msvc"
FILES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")


def main() -> None:
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked",
             "--filter-platform", TARGET],
            text=True, encoding="utf-8",
        )
    )
    by_id = {p["id"]: p for p in meta["packages"]}
    # Keep only packages reachable through non-dev dependency edges.
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for dep in nodes[i]["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds <= {"dev"}:
                continue
            stack.append(dep["pkg"])
    pkgs = sorted((by_id[i] for i in seen if i != root), key=lambda p: (p["name"], p["version"]))

    out = []
    w = out.append
    w("# Third-party licenses\n")
    w("Openify is licensed under GPL-3.0-or-later (see `LICENSE`). It includes the "
      "following third-party components. Generated by `scripts/third_party_licenses.py`; "
      "do not edit by hand.\n")
    w("Fonts (Figtree, Plus Jakarta Sans: SIL OFL 1.1) and icons (Lucide: ISC) are in "
      "`assets/`, with their licenses in `assets/licenses/`.\n")
    w("Headphone equalizer profiles come from OPRA (https://github.com/opra-project/OPRA, "
      "data CC BY-SA 4.0, code MIT). They are not shipped: the app downloads them when you "
      "first search for a headphone profile; each selected profile is credited in the "
      "settings, with a notice in `assets/licenses/OPRA-NOTICE.txt`.\n")
    w("## Crates\n")
    w("| Crate | Version | License | Source |")
    w("|---|---|---|---|")
    texts = {}
    for p in pkgs:
        lic = (p.get("license") or "see license file").replace("|", "/")
        src = p.get("repository") or p.get("homepage") or ""
        local = " (patched copy in vendor/)" if (p.get("source") is None) else ""
        w(f"| {p['name']} | {p['version']} | {lic}{local} | {src} |")
        d = pathlib.Path(p["manifest_path"]).parent
        for f in sorted(d.iterdir()):
            if f.is_file() and f.name.upper().startswith(FILES):
                try:
                    t = f.read_text(encoding="utf-8", errors="replace").strip()
                except OSError:
                    continue
                h = hashlib.sha256(t.encode()).hexdigest()
                texts.setdefault(h, (t, []))[1].append(f"{p['name']} {p['version']}")
    w("\n## License and notice texts\n")
    w("Each text appears once, followed by the crates that ship it.\n")
    for t, users in sorted(texts.values(), key=lambda x: x[1][0]):
        w("---\n")
        w("Used by: " + ", ".join(sorted(set(users))) + "\n")
        w("```text")
        w(t)
        w("```\n")
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
